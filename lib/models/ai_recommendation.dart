import 'risk_level.dart';

/// Categories of AI-driven digital twin insights
enum RecommendationCategory {
  harvestTiming,
  marketArbitrage,
  storageDecision,
  logisticsOptimization,
  smartFinancing;

  String get displayName {
    switch (this) {
      case RecommendationCategory.harvestTiming:
        return 'Harvest Timing';
      case RecommendationCategory.marketArbitrage:
        return 'Market Arbitrage';
      case RecommendationCategory.storageDecision:
        return 'Storage & Shelf-Life';
      case RecommendationCategory.logisticsOptimization:
        return 'Logistics Route';
      case RecommendationCategory.smartFinancing:
        return 'Warehouse Financing';
    }
  }
}

/// Core AI recommendation generated by AgriTwin AI digital twin engine
class AiRecommendation {
  final String id;
  final String title;
  final String description;
  final RecommendationCategory category;
  final String recommendedAction;
  final String projectedOutcome; // e.g. "+₹14,500 additional profit"
  final double confidenceScore; // e.g. 0.92 (92%)
  final RiskLevel riskLevel;
  final DateTime generatedAt;
  final bool isActionable;

  const AiRecommendation({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.recommendedAction,
    required this.projectedOutcome,
    required this.confidenceScore,
    required this.riskLevel,
    required this.generatedAt,
    this.isActionable = true,
  });
}
