  /// Helper to get current active language code ('en', 'mr', 'hi')
  static String get currentLangCode {
    final lang = MockData.activeLanguage.toLowerCase();
    if (lang.contains('marathi') || lang.contains('मराठी') || lang == 'mr') {
      return 'mr';
    } else if (lang.contains('hindi') || lang.contains('हिंदी') || lang == 'hi') {
      return 'hi';
    }
    return 'en';
  }

  /// Change active language and notify all listening widgets to rebuild UI
  static void setLanguage(String newLanguage) {
    MockData.activeLanguage = newLanguage;
    languageNotifier.value = newLanguage;
  }

  /// Translate any string based on current selected language in MockData
  static String tr(String text) {
    final code = currentLangCode;
    if (code == 'en') return text;
    final map = _translations[code];
    if (map != null && map.containsKey(text)) {
      return map[text]!;
    }

    // Dynamic partial replacements for composite strings
    String result = text;
    final replacements = _dynamicSubstitutions[code];
    if (replacements != null) {
      for (final entry in replacements.entries) {
        if (result.contains(entry.key)) {
          result = result.replaceAll(entry.key, entry.value);
        }
      }
    }
    return result;
  }

